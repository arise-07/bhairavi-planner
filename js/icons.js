/**
 * Return an SVG string. Decorative by default (aria-hidden); pass `label` for a meaningful icon.
 */
export function icon(name, { size = 18, cls = '', label = '' } = {}) {
  const body = PATHS[name] || '';
  const a11y = label
    ? `role="img" aria-label="${label.replace(/"/g, '&quot;')}"`
    : 'aria-hidden="true" focusable="false"';
  return `<svg class="icon ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${body}</svg>`;
}

/** Replace static `<span data-icon="name">` placeholders in the HTML. */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.dataset.iconReady) return;
    el.insertAdjacentHTML('afterbegin', icon(el.dataset.icon, { size: Number(el.dataset.size) || 18 }));
    el.classList.add('icon-wrap');
    el.dataset.iconReady = '1';
  });
}
